
from typing import Literal

from pydantic import BaseModel


AnalysisType = Literal[
    "groupby_aggregation_desc",
    "groupby_aggregation_asc",
    "time_trend",
    "distribution",
    "correlation",
    "average_metric",
    "total_metric",
    "missing_value_summary",
    "general_summary",
    "unsupported",
]


class LLMAnalysisPlan(BaseModel):
    """
    Structured analysis plan generated by the LLM.

    Column names are validated separately before execution.
    """
    analysis_type: AnalysisType
    metric_columns: list[str]
    group_column: str | None
    date_column: str | None
    steps: list[str]
    supported: bool
    explanation: str
